def _price_number(text):
    """从单元格文本中解析数值，容忍货币符号、千位分隔符与"元"字后缀。"""
    s = (text or "").strip()
    s = s.replace(",", "").replace("，", "").replace(" ", "")
    for token in ("¥", "￥", "RMB", "rmb", "元", "圆"):
        s = s.replace(token, "")
    if not re.match(r"^\d+(\.\d+)?$", s):
        return None
    return Decimal(s)


def _price_hit(rec):
    """该价格是否已正确换算为 基准值×1.1（四舍五入取整）。"""
    if not rec["base"]:
        return False
    expect = _x11(rec["base"])
    got = _price_number(rec["text"])
    if expect is None or got is None:
        return False
    return int(got.quantize(Decimal("1"), rounding=ROUND_HALF_UP)) == expect


def _subset(prices, kind, keys=None, labels=None):
    out = []
    for rec in prices:
        if rec["kind"] != kind:
            continue
        if keys is not None and rec["key"] not in keys:
            continue
        if labels is not None and rec["label"] not in labels:
            continue
        out.append(rec)
    return out


def _all_hit(recs, expect_count=None):
    if not recs:
        return False, "未采集到价格单元格"
    if expect_count is not None and len(recs) != expect_count:
        return False, "价格处数为 %d，应为 %d" % (len(recs), expect_count)
    bad = [r for r in recs if not _price_hit(r)]
    if bad:
        sample = "、".join("%s %s=%s" % (r["key"], r["label"], r["text"] or "空") for r in bad[:4])
        return False, "未正确换算 %d 处：%s" % (len(bad), sample)
    return True, "%d 处全部正确" % len(recs)


