def _cell_paras(cell):
    return [p._p for p in cell.paragraphs if _para_text(p._p).strip()]


def _page_feat_text(tbl):
    for row in tbl.rows:
        for cell in _uniq_cells(row):
            for sub in cell.tables:
                head = _uniq_cells(sub.rows[0])
                if head and head[0].text.strip().startswith("产品特点"):
                    return _FEAT_SEP.join(c.text.strip() for c in head), sub
    return None, None


