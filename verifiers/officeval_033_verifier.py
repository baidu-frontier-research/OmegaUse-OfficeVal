def _sig_broken(styles, pindex, expected):
    """expected = (对齐, [(文字, 西文, 中文, 字号, 颜色), ...])；返回 (是否被破坏, 说明)。"""
    jc, runs = expected
    full = "".join(r[0] for r in runs)
    hits = pindex.get(full)
    if not hits:
        return True, "缺失或被改写：%s" % full[:24]
    for pel in hits:
        got_jc, got_runs = _para_signature(styles, pel)
        if got_jc == jc and list(got_runs) == list(runs):
            return False, ""
    got_jc, got_runs = _para_signature(styles, hits[0])
    return True, "格式被改动：%s 实测 %s / %s" % (full[:16], got_jc, got_runs)


def _fmt_broken(styles, pel, fmt):
    """按 (对齐, 西文字体, 字号, 颜色) 校验段落内全部 run。"""
    jc, font, size, color = fmt
    got_jc, runs = _para_signature(styles, pel)
    if got_jc != jc:
        return "对齐为 %s" % got_jc
    if not runs:
        return "无文字"
    for run in runs:
        if run[1] != font or run[3] != size or run[4] != color:
            return "字体/字号/颜色为 %s/%s/%s" % (run[1], run[3], run[4])
    return ""


