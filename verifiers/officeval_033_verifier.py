def _x11(text):
    """按四舍五入取整计算 ×1.1 后的应有数值；无法解析时返回 None。"""
    s = (text or "").strip()
    if not re.match(r"^\d+$", s):
        return None
    return int((Decimal(s) * Decimal("1.1")).quantize(Decimal("1"), rounding=ROUND_HALF_UP))


