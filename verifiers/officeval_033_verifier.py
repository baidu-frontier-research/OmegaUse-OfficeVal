def _split_ref(rows):
    return dict((r.split("|")[0], r.split("|")) for r in rows)


def _price_records(groups):
    """采集全册价格单元格：kind / key / 列名 / 单元格对象 / 原文 / 换算前基准值。"""
    erp_ref = _split_ref(REF_ERP)
    pei_ref = _split_ref(REF_PEI)
    cus_ref = _split_ref(REF_CUS)
    out = []

    def add(kind, key, label, cell, base):
        out.append({"kind": kind, "key": key, "label": label, "cell": cell,
                    "text": cell.text.strip() if cell is not None else "", "base": base})

    for tbl in groups["ERP"]:
        for row in tbl.rows[1:]:
            cells = _uniq_cells(row)
            code = cells[0].text.strip()
            if len(cells) > 3:
                add("ERP", code, "零售价（元）", cells[3],
                    erp_ref[code][3] if code in erp_ref else None)
    for tbl in groups["PEI"]:
        for row in tbl.rows[1:]:
            cells = _uniq_cells(row)
            code = cells[0].text.strip()
            if len(cells) > 2:
                add("PEI", code, "零售价（元）", cells[2],
                    pei_ref[code][2] if code in pei_ref else None)
    for tbl in groups["CUS"]:
        for row in tbl.rows[1:]:
            cells = _uniq_cells(row)
            code = cells[0].text.strip()
            ref = cus_ref.get(code)
            for idx in range(3, 10):
                if idx >= len(cells):
                    continue
                label = "A%d" % (idx - 2) if idx <= 8 else "标准零售价"
                add("CUS", code, label, cells[idx], ref[idx] if ref else None)
    for tbl in groups["CVT"]:
        for ridx, row in enumerate(tbl.rows[1:]):
            cells = _uniq_cells(row)
            ref = _REF_CONVERT[ridx] if ridx < len(_REF_CONVERT) else None
            for idx, label in ((1, "基础零售价（元）"), (4, "核算后零售价（元）")):
                if idx < len(cells):
                    add("CVT", "第%d行" % (ridx + 1), label, cells[idx],
                        ref[1 if idx == 1 else 4] if ref else None)
    for tbl in groups["REC"]:
        for ridx, row in enumerate(tbl.rows[1:]):
            cells = _uniq_cells(row)
            ref = _REF_RECORD[ridx] if ridx < len(_REF_RECORD) else None
            if len(cells) > 5:
                add("REC", "序号%d" % (ridx + 1), "零售价（元）", cells[5],
                    ref[5] if ref else None)
    return out


