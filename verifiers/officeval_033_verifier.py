def _evaluate_impl(file_path, result):
    # 维度一的第一道门禁：交付物格式只接受 .docx，不合格即判 0，不再解析内容。
    # 此时拿不到各条细则原文（rule 文本要靠解析文档才能生成），故 dim2 不出项，
    # 与「文档打不开」的异常口径一致。
    reject = _fmt_reject(file_path)
    if reject:
        result["dim1_pass"] = False
        result["dim1_reason"] = "维度一未通过：%s，完成度总分记 0" % reject
        result["dim2_items"] = []
        result["total_score"] = 0
        return result

    doc = _open_word_document(file_path)
    pkg = _load_package(file_path)
    styles = _build_styles(doc)
    paras = list(pkg["doc"].iter(qn("w:p")))
    flat = _flat_tables(doc.tables)
    groups = _classify_tables(flat)
    prices = _price_records(groups)
    pindex = _para_index(styles, paras)
    pages = _product_pages(doc)

    dim1_pass, dim1_reason = _check_dim1(flat, prices)
    result["dim1_pass"] = dim1_pass
    # 维度一未通过时，dim1_reason 必须带上错误摘要，便于直接定位原因
    result["dim1_reason"] = (dim1_reason if dim1_pass
                             else "维度一未通过：%s，完成度总分记 0" % dim1_reason)

    checks = _collect_positive(prices)
    checks += _collect_penalty(doc, pkg, styles, flat, groups,
                              prices, pindex, pages, paras)
    items = []
    total = 0
    for (hit, rule, _detail), max_delta in zip(checks, _MAX_DELTAS_ORDER):
        if not dim1_pass:
            hit = False
        delta = max_delta if hit else 0
        total += delta
        items.append({"rule": rule, "max_delta": max_delta, "delta": delta,
                      "hit": hit})
    result["dim2_items"] = items
    result["total_score"] = 0 if not dim1_pass else max(0, total)
    return result


def evaluate(dir_path):
    """在 dir_path 内定位待评估的 .docx 并返回评分字典。

    - 交付物只接受 .docx：目录内优先取 .docx；若只交了 .doc / .rtf / .odt / .pdf 等
      其他格式，仍把它收作被评对象，由维度一判不通过（total_score 记 0），而不是当成
      「没有交付物」跳过评测。
    - 定位不到被评估文件时：error 只回纯文本原因（不带异常类名），
      dim1_pass 与 dim1_reason 一律留空（空字符串，表示维度一根本没进入判定），
      dim2_items=[]、total_score=max_score=0。
    - 维度一未通过时：dim1_pass=False，且 dim1_reason 带出错误摘要。
    """
    result = {"id": SCRIPT_ID, "file_name": "", "status": "ok", "error": None,
              "dim1_pass": False, "dim1_reason": "", "dim2_items": [],
              "total_score": 0, "max_score": MAX_SCORE_TOTAL}
    try:
        if not dir_path or not os.path.isdir(dir_path):
            raise FileNotFoundError("目录不存在或不是目录：%s" % dir_path)
        files = [name for name in sorted(os.listdir(dir_path))
                 if not name.startswith("~$")
                 and os.path.isfile(os.path.join(dir_path, name))]
        cands = [n for n in files if n.lower().endswith(_ACCEPTED_EXT)]
        if not cands:
            cands = [n for n in files if n.lower().endswith(_WRONG_FMT_EXTS)]
        if not cands:
            raise FileNotFoundError("目录中未找到 .docx 文件：%s" % dir_path)
        target = os.path.join(dir_path, cands[0])
        result["file_name"] = os.path.basename(target)
        _evaluate_impl(target, result)
    except FileNotFoundError as exc:
        # 找不到被评估文件：error 只回传纯文本原因，不带异常类名；维度一根本没进入
        # 判定，dim1_pass 与 dim1_reason 一律留空（空字符串，而非 False），满分归零
        result["status"] = "error"
        result["error"] = str(exc)
        result["file_name"] = ""
        result["dim1_pass"] = ""
        result["dim1_reason"] = ""
        result["dim2_items"] = []
        result["total_score"] = 0
        result["max_score"] = 0
    except Exception as exc:                                # noqa: BLE001
        # 文件在但打不开/解析失败：维度一未通过，dim1_reason 带上错误摘要便于定位
        result["status"] = "error"
        result["error"] = "脚本运行异常：%s: %s" % (type(exc).__name__, exc)
        result["dim1_pass"] = False
        result["dim1_reason"] = "文档无法打开或解析：%s: %s" % (type(exc).__name__, exc)
        result["dim2_items"] = []
        result["total_score"] = 0
    return result


