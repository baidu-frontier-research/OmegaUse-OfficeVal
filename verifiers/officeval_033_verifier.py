def _build_styles(doc):
    """建立样式索引，用于把 run 的字体/字号/颜色解析到最终生效值。"""
    el = doc.styles.element
    info = {}
    default_pid = None
    for st in el.findall(qn("w:style")):
        sid = st.get(qn("w:styleId"))
        based = st.find(qn("w:basedOn"))
        info[sid] = {
            "basedOn": based.get(qn("w:val")) if based is not None else None,
            "rPr": st.find(qn("w:rPr")),
            "pPr": st.find(qn("w:pPr")),
        }
        if st.get(qn("w:type")) == "paragraph" and st.get(qn("w:default")) == "1":
            if default_pid is None:
                default_pid = sid
    dd_rpr = None
    dd_ppr = None
    dd = el.find(qn("w:docDefaults"))
    if dd is not None:
        rd = dd.find(qn("w:rPrDefault"))
        if rd is not None:
            dd_rpr = rd.find(qn("w:rPr"))
        pd = dd.find(qn("w:pPrDefault"))
        if pd is not None:
            dd_ppr = pd.find(qn("w:pPr"))
    return {"info": info, "default": default_pid, "dd_rpr": dd_rpr, "dd_ppr": dd_ppr}


def _rpr_value(rpr, key):
    if rpr is None:
        return None
    if key in ("ascii", "eastAsia", "hAnsi"):
        f = rpr.find(qn("w:rFonts"))
        return f.get(qn("w:" + key)) if f is not None else None
    node = rpr.find(qn("w:" + key))
    if node is None:
        return None
    return node.get(qn("w:val"))


def _style_chain_value(styles, style_id, key, is_run=True):
    sid = style_id
    seen = set()
    while sid and sid in styles["info"] and sid not in seen:
        seen.add(sid)
        holder = styles["info"][sid]["rPr" if is_run else "pPr"]
        val = _rpr_value(holder, key) if is_run else _ppr_value(holder, key)
        if val:
            return val
        sid = styles["info"][sid]["basedOn"]
    return None


def _ppr_value(ppr, key):
    if ppr is None:
        return None
    node = ppr.find(qn("w:" + key))
    if node is None:
        return None
    return node.get(qn("w:val"))


def _para_style_id(styles, pel):
    ppr = pel.find(qn("w:pPr")) if pel is not None else None
    if ppr is not None:
        ps = ppr.find(qn("w:pStyle"))
        if ps is not None and ps.get(qn("w:val")):
            return ps.get(qn("w:val"))
    return styles["default"]


def _resolve_run_value(styles, pel, rel, key):
    """run 直接属性 → 段落样式（含 basedOn 链）→ docDefaults。"""
    val = _rpr_value(rel.find(qn("w:rPr")) if rel is not None else None, key)
    if val:
        return val
    val = _style_chain_value(styles, _para_style_id(styles, pel), key, is_run=True)
    if val:
        return val
    return _rpr_value(styles["dd_rpr"], key)


def _resolve_jc(styles, pel):
    ppr = pel.find(qn("w:pPr")) if pel is not None else None
    val = _ppr_value(ppr, "jc")
    if not val:
        val = _style_chain_value(styles, _para_style_id(styles, pel), "jc", is_run=False)
    if not val:
        val = _ppr_value(styles["dd_ppr"], "jc")
    if val in ("both", "start", "justify", None):
        return "left"
    if val == "end":
        return "right"
    return val


def _run_text(rel):
    return "".join(t.text or "" for t in rel.iter(qn("w:t")))


def _para_text(pel):
    return "".join(t.text or "" for t in pel.iter(qn("w:t")))


def _para_signature(styles, pel):
    """返回 (对齐, [(文字, 西文字体, 中文字体, 字号, 颜色), ...])，相邻同格式 run 合并。"""
    merged = []
    for rel in pel.findall(qn("w:r")):
        txt = _run_text(rel)
        if not txt:
            continue
        key = (_resolve_run_value(styles, pel, rel, "ascii"),
               _resolve_run_value(styles, pel, rel, "eastAsia"),
               _resolve_run_value(styles, pel, rel, "sz"),
               _resolve_run_value(styles, pel, rel, "color"))
        if merged and merged[-1][1] == key:
            merged[-1][0] += txt
        else:
            merged.append([txt, key])
    return _resolve_jc(styles, pel), [tuple([t] + list(k)) for t, k in merged]


def _uniq_cells(row):
    seen = set()
    out = []
    for cell in row.cells:
        key = id(cell._tc)
        if key in seen:
            continue
        seen.add(key)
        out.append(cell)
    return out


def _row_text(row):
    return [c.text.strip() for c in _uniq_cells(row)]


def _flat_tables(tables, seen=None):
    """按文档顺序递归收集全部表格（含嵌套表），并按元素去重。"""
    if seen is None:
        seen = set()
    out = []
    for tbl in tables:
        if id(tbl._tbl) in seen:
            continue
        seen.add(id(tbl._tbl))
        out.append(tbl)
        for row in tbl.rows:
            for cell in _uniq_cells(row):
                out.extend(_flat_tables(cell.tables, seen))
    return out


def _load_package(file_path):
    """读取包内原始部件，用于图形字节、底纹边框、节属性与保护状态的指纹比对。"""
    pkg = {"names": [], "doc": None, "settings": None, "pages": None, "media": []}
    with zipfile.ZipFile(file_path) as zf:
        pkg["names"] = [n for n in zf.namelist() if not n.endswith("/")]
        pkg["doc"] = ET.fromstring(zf.read("word/document.xml"))
        if "word/settings.xml" in pkg["names"]:
            pkg["settings"] = ET.fromstring(zf.read("word/settings.xml"))
        if "docProps/app.xml" in pkg["names"]:
            app = ET.fromstring(zf.read("docProps/app.xml"))
            for node in app.iter():
                if node.tag.endswith("}Pages") and (node.text or "").strip().isdigit():
                    pkg["pages"] = int(node.text.strip())
        media = sorted(n for n in pkg["names"] if n.startswith("word/media/"))
        pkg["media"] = [hashlib.md5(zf.read(n)).hexdigest() for n in media]
    return pkg


def _digest(items):
    return hashlib.md5("|".join(items).encode("utf-8")).hexdigest()


def _media_fingerprint(pkg):
    return _digest(sorted(pkg["media"]))


def _extent_fingerprint(root):
    return _digest(["%s,%s" % (e.get("cx"), e.get("cy")) for e in root.iter(qn("wp:extent"))])


def _shading_fingerprint(root):
    counter = {}
    for node in root.iter(qn("w:shd")):
        fill = node.get(qn("w:fill"))
        counter[fill] = counter.get(fill, 0) + 1
    return _digest(["%s=%d" % (k, v) for k, v in sorted(counter.items(), key=lambda x: str(x[0]))])


def _border_fingerprint(root):
    counter = {}
    for node in root.iter(qn("w:tcBorders")):
        for child in node:
            key = "%s:%s:%s:%s" % (child.tag.split("}")[-1], child.get(qn("w:val")),
                                   child.get(qn("w:sz")), child.get(qn("w:color")))
            counter[key] = counter.get(key, 0) + 1
    return _digest(["%s=%d" % (k, v) for k, v in sorted(counter.items())])


_RE_ERP_CODE = re.compile(r"^Q\d{4}-\d{3}$")
_RE_PEI_CODE = re.compile(r"^P\d{7}$")
_RE_CUS_CODE = re.compile(r"^YQ-\d{2}-\d{2}$")
_RE_MAT_CODE = re.compile(r"^MT-\d{3}$")
_RE_REC_CODE = re.compile(r"^YQ\d{3}-\d{3}$")


def _classify_tables(flat):
    """按表头文字或首行数据特征识别各类表格，表头被改写时仍可靠首行特征命中。"""
    groups = {k: [] for k in ("ERP", "PEI", "CUS", "FAB", "SIZ",
                              "MAT", "ORD", "CVT", "REC", "FEAT")}
    for tbl in flat:
        rows = tbl.rows
        if not rows:
            continue
        head = tuple(_row_text(rows[0]))
        if len(rows) == 1:
            if head and head[0].startswith("产品特点"):
                groups["FEAT"].append(tbl)
            continue
        first = _row_text(rows[1])
        # 规则页表格首行为跨列合并的标题行，此时真正的表头在第 2 行
        if len(rows) > 2 and len(head) < len(first):
            head = tuple(first)
            first = _row_text(rows[2])
        width = len(first)
        if head == _HEAD_ERP or (width == 5 and _RE_ERP_CODE.match(first[0])):
            groups["ERP"].append(tbl)
        elif head == _HEAD_PEI or (width == 4 and _RE_PEI_CODE.match(first[0])):
            groups["PEI"].append(tbl)
        elif head == _HEAD_CUS or (width == 10 and _RE_CUS_CODE.match(first[0])):
            groups["CUS"].append(tbl)
        elif head == tuple(_REF_FABRIC[0]) or (width == 3 and first[0] == "面料等级"):
            groups["FAB"].append(tbl)
        elif head == tuple(_REF_SIZE_RANGE[0]) or (width == 3 and first[0] in ("沙发总宽", "躺位总深")):
            groups["SIZ"].append(tbl)
        elif head == tuple(_REF_MATERIAL[0]) or (width == 5 and _RE_MAT_CODE.match(first[0])):
            groups["MAT"].append(tbl)
        elif head == tuple(_REF_ORDER_FLOW[0]) or (width == 3 and first[0] == "选型"):
            groups["ORD"].append(tbl)
        elif head == _REF_CONVERT_HEAD or (width == 5 and first[2].endswith("%")):
            groups["CVT"].append(tbl)
        elif head == _REF_RECORD_HEAD or (width == 7 and _RE_REC_CODE.match(first[1])):
            groups["REC"].append(tbl)
    return groups


