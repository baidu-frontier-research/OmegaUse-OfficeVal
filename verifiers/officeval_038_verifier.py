    #   ① 每处回填内容长度恰为 1（不出现"（ A ）""（AB）""（）"）
    #   ② 题号段内无制表符，且回填括号后不出现 2 个以上连续空格
    # 不同办公软件对齐：制表符在 OOXML 里是 w:tab，python-docx 读回文本为 \t，两家一致。
    tab_bad = sum(1 for p in stems
                  if '\t' in p.text or re.search(r'（[A-D√×]）\s{2,}', p.text))
    place_bad = sum(1 for src in (dan, pan) for v in src.values()
                    if v is None or len(v) != 1)
    r10_ok = (place_bad == 0 and tab_bad == 0)
    if r10_ok:
        results.append("+3：答案落位规范——括号内仅 1 个字符，括号前无制表符或多余空格填充")
    else:
        results.append("+0：答案落位规范——括号内仅 1 个字符，括号前无制表符或多余空格填充")

    # +3：题干与选项字体为宋体系（SimSun / 宋体 / NSimSun / 中易宋体）
    #   ① 题干与选项的每个有字 run 都解析出生效字体
    #   ② 生效字体名归一后必须落在宋体系内
    # 不同办公软件对齐：按 Word 继承链解析 w:rFonts/@w:eastAsia（缺省回落 @w:ascii/@w:hAnsi）
    # → 段落样式 basedOn 链 → docDefaults，取"打开后眼睛看到的字体"。
    fonts = [(_resolve_effective_font(doc, r) or '')
             for p in body for r in p.runs if r.text.strip()]
    r11_ok = (len(fonts) > 0 and all(_is_songti(f) for f in fonts))
    if r11_ok:
        results.append("+3：题干与选项字体为宋体系（SimSun / 宋体 / NSimSun / 中易宋体）")
    else:
        results.append("+0：题干与选项字体为宋体系（SimSun / 宋体 / NSimSun / 中易宋体）")

    # +3：题干与选项字号在 12.2—14.2pt 区间
    #   ① 题干与选项的每个有字 run 都解析出生效字号
    #   ② 生效字号必须落在 12.2—14.2pt（原稿实测 13.20pt，上下各留约 1pt）
    # 不同办公软件对齐：w:sz 为半磅整数，Word 与 WPS 写法一致；缺省沿样式链到 docDefaults。
    sizes = [s for s in (_resolve_effective_size_pt(doc, r)
                         for p in body for r in p.runs if r.text.strip()) if s]
    r12_ok = (len(sizes) > 0 and all(SZ_BODY[0] <= s <= SZ_BODY[1] for s in sizes))
    if r12_ok:
        results.append("+3：题干与选项字号在 12.2—14.2pt 区间")
    else:
        results.append("+0：题干与选项字号在 12.2—14.2pt 区间")

    # +3：正文行距为 1.0—1.25 倍或固定值 16.2—20.2pt，且段前+段后间距 ≤4pt
    #   ① 倍数行距落在 1.0—1.25 倍，或固定/最小行距落在 16.2—20.2pt（原稿 18.20pt）
    #   ② 任一段落的段前 + 段后 ≤4pt（原稿逐行等距、无段间距）
    # 不同办公软件对齐：w:spacing/@w:line + @w:lineRule（auto=1/240 倍，exact|atLeast=1/20 磅），
    # python-docx 已把两种口径分别还原为 float 倍数与 Length（.pt）。
    lsp, spc = set(), 0.0
    for p in body:
        pf = p.paragraph_format
        v = pf.line_spacing
        if v is None:
            lsp.add(('multi', 1.0))               # 未设置 = 单倍行距
        elif hasattr(v, 'pt'):
            lsp.add(('exact', round(v.pt, 1)))
        else:
            lsp.add(('multi', round(float(v), 2)))
        spc = max(spc, (pf.space_before.pt if pf.space_before else 0)
                  + (pf.space_after.pt if pf.space_after else 0))
    ls_ok = all((k == 'multi' and LINE_MULT[0] <= v <= LINE_MULT[1])
                or (k == 'exact' and LINE_PT[0] <= v <= LINE_PT[1]) for k, v in lsp)
    r13_ok = (ls_ok and spc <= SPACE_MAX)
    if r13_ok:
        results.append("+3：正文行距为 1.0—1.25 倍或固定值 16.2—20.2pt，且段前+段后间距 ≤4pt")
    else:
        results.append("+0：正文行距为 1.0—1.25 倍或固定值 16.2—20.2pt，且段前+段后间距 ≤4pt")

    # +3：回填答案字符与所在题干同字体同字号，无加粗/斜体/下划线/彩色/高亮
    #   ① 回填字符（单独成 run 的 A/B/C/D/√/×）不得加粗、斜体、下划线
    #   ② 不得设非黑文字色（彩色即视为不一致）
    #   ③ 生效字体与字号必须与本段第一个有字 run 相同
    # 不同办公软件对齐：w:b / w:i / w:u / w:color / w:highlight 均在 run 的 rPr 上，
    # 手工输入答案时若继承了"上一次输入格式"就会在此暴露。
    fmt_bad = 0
    for p in stems:
        base = None
        for r in p.runs:
            if r.text.strip() and base is None:
                base = (_resolve_effective_font(doc, r), _resolve_effective_size_pt(doc, r))
            if r.text.strip() and re.fullmatch(r'[A-D√×]', r.text.strip()):
                col = r.font.color
                if r.bold or r.italic or r.underline or (
                        col is not None and col.rgb is not None and str(col.rgb) != '000000'):
                    fmt_bad += 1
                elif base and (_resolve_effective_font(doc, r),
                               _resolve_effective_size_pt(doc, r)) != base:
                    fmt_bad += 1
    r14_ok = (fmt_bad == 0)
    if r14_ok:
        results.append("+3：回填答案字符与所在题干同字体同字号，无加粗/斜体/下划线/彩色/高亮")
    else:
        results.append("+0：回填答案字符与所在题干同字体同字号，无加粗/斜体/下划线/彩色/高亮")

    # +3：页眉层含「菟思学院」文字，字号 10.0—11.0pt，颜色为黑色/自动/灰色（非彩色、非近白）
    #   ① 任一 header*.xml 的文字层含"菟思学院"
    #   ② 该页眉部件内存在字号落在 10.0—11.0pt 的设定（原稿实测 10.50pt）
    #   ③ 颜色不得是彩色（RGB 极差 >40）或近白（平均亮度 >0xE0，等于看不见）
    # 说明：页眉在 Word 里本就淡显，黑色/自动/灰色都合规——若真设成灰色反而接近白色。
    # 不同办公软件对齐：页眉一律落在 word/header*.xml，w:sz 半磅、w:color 六位十六进制。
    hdr_xmls = _parts_like(parts, 'word/header')
    hdr_text_ok = hdr_size_ok = False
    hdr_color_ok = True
    for x in hdr_xmls:
        if HDR_TEXT in _plain_text(x):
            hdr_text_ok = True
            for m in re.finditer(r'<w:sz w:val="(\d+)"', x):
                if SZ_HDRTXT[0] <= int(m.group(1)) / 2 <= SZ_HDRTXT[1]:
                    hdr_size_ok = True
            for m in re.finditer(r'<w:color w:val="([0-9A-Fa-f]{6})"', x):
                v = m.group(1).upper()
                cr, cg, cb = (int(v[i:i + 2], 16) for i in (0, 2, 4))
                if max(cr, cg, cb) - min(cr, cg, cb) > 40 or (cr + cg + cb) // 3 > 0xE0:
                    hdr_color_ok = False
    r15_ok = (hdr_text_ok and hdr_size_ok and hdr_color_ok)
    if r15_ok:
        results.append("+3：页眉层含「菟思学院」文字，字号 10.0—11.0pt，颜色为黑色/自动/灰色（非彩色、非近白）")
    else:
        results.append("+0：页眉层含「菟思学院」文字，字号 10.0—11.0pt，颜色为黑色/自动/灰色（非彩色、非近白）")

    # +3：存在「菟思学院」水印，三种实现任选其一
    #   ①艺术字或办公软件自带水印（灰色、倾斜 25°—45°、形高 55—85pt）
    #   ②页眉图片水印（显示尺寸 ≥150pt）
    #   ③文本框水印且衬于文字下方
    # 三种实现之间是"或"，每种实现内部的子条件是"且"；详见 _check_watermark。
    r16_ok, _wm_detail = _check_watermark(parts)
    if r16_ok:
        results.append("+3：存在「菟思学院」水印，三种实现任选其一：①艺术字或办公软件自带水印"
                       "（灰色、倾斜 25°—45°、形高 55—85pt）②页眉图片水印（显示尺寸 ≥150pt）"
                       "③文本框水印且衬于文字下方")
    else:
        results.append("+0：存在「菟思学院」水印，三种实现任选其一：①艺术字或办公软件自带水印"
                       "（灰色、倾斜 25°—45°、形高 55—85pt）②页眉图片水印（显示尺寸 ≥150pt）"
                       "③文本框水印且衬于文字下方")

    # +3：版面设置——A4 21.0×29.7cm(±0.2) 纵向；左 1.55—2.55、右 0.6—2.6、上 0.9—2.0、
    #     下 1.3—2.7cm；页眉距顶端 0.3—0.8cm；总页数 86—110 页
    #   ① 每个节的页宽/页高都是 A4 纵向（21.0 × 29.7cm，容差 ±0.2cm）
    #   ② 每个节的四边距都落在各自区间（区间来自原稿几何反推，见文件头常量说明）
    #   ③ 每个节的页眉距顶端落在 0.3—0.8cm（原稿 0.45cm）
    #   ④ 总页数落在 86—110 页（原稿 96 页）
    # 不同办公软件对齐：版面全部读 w:sectPr/w:pgMar 与 w:pgSz（缇，1cm=567 缇），
    # 逐节检查以免"只有第一节合规、其余节被转换器改坏"；页数取 docProps/app.xml 的
    # <Pages>（Word 与 WPS 保存时都会回写该缓存值）。
    layout_ok, layout_bad = True, []
    for s in doc.sections:
        got = {'左': s.left_margin, '右': s.right_margin,
               '上': s.top_margin, '下': s.bottom_margin}
        for k, (_base, lo, hi) in MARGIN.items():
            v = got[k].cm if got[k] is not None else 0.0
            if not lo <= v <= hi:
                layout_ok = False
                layout_bad.append(f'{k}{v:.2f}')
        for nm, val, lo, hi in (('宽', s.page_width, PAGE_W - 0.2, PAGE_W + 0.2),
                                ('高', s.page_height, PAGE_H - 0.2, PAGE_H + 0.2)):
            vv = val.cm if val is not None else 0.0
            if not lo <= vv <= hi:
                layout_ok = False
                layout_bad.append(f'{nm}{vv:.2f}')
        hd = s.header_distance.cm if s.header_distance is not None else 0.0
        if not HDR_DIST[1] <= hd <= HDR_DIST[2]:
            layout_ok = False
            layout_bad.append(f'页眉距{hd:.2f}')
    pages = 0
    for x in _parts_like(parts, 'docProps/app.xml'):
        m = re.search(r'<Pages>(\d+)</Pages>', x)
        pages = int(m.group(1)) if m else 0
    if not PAGES[0] <= pages <= PAGES[1]:
        layout_ok = False
        layout_bad.append(f'页数{pages}')
    if layout_ok:
        results.append("+3：版面设置——A4 21.0×29.7cm(±0.2) 纵向；左 1.55—2.55、右 0.6—2.6、"
                       "上 0.9—2.0、下 1.3—2.7cm；页眉距顶端 0.3—0.8cm；总页数 86—110 页")
    else:
        results.append("+0：版面设置——A4 21.0×29.7cm(±0.2) 纵向；左 1.55—2.55、右 0.6—2.6、"
                       "上 0.9—2.0、下 1.3—2.7cm；页眉距顶端 0.3—0.8cm；总页数 86—110 页")

    # +1：3 个题目区标题独立成段且各出现 1 次：主标题、「一、单选题」、「二、判断题」
    #   ① 三个标题文本各自单独成段（整段文字恰好等于标题本身）
    #   ② 三者出现次数都恰为 1（不重复、不缺失）
    # 不同办公软件对齐：只比对段落纯文本，不要求使用"标题"样式。
    title_cnt = {}
    for t in qtexts:
        s = t.strip()
        if s in TITLES:
            title_cnt[s] = title_cnt.get(s, 0) + 1
    r18_ok = (title_cnt == TITLES)
    if r18_ok:
        results.append("+1：3 个题目区标题独立成段且各出现 1 次：主标题、「一、单选题」、「二、判断题」")
    else:
        results.append("+0：3 个题目区标题独立成段且各出现 1 次：主标题、「一、单选题」、「二、判断题」")

    # +1：题目区空段落占比 ≤1%
    #   ① 空段落（去空白后为空的 w:p）数量 ÷ 题目区段落总数 ≤1%
    # 不同办公软件对齐：PDF 转换常用空段落充当行距，这里限制其比例而非绝对禁止。
    empty_n = sum(1 for t in qtexts if not t.strip())
    empty_ratio = empty_n / max(1, len(qtexts))
    r19_ok = (empty_ratio <= EMPTY_RATIO_MAX)
    if r19_ok:
        results.append("+1：题目区空段落占比 ≤1%")
    else:
        results.append("+0：题目区空段落占比 ≤1%")

    # +1：无修订标记（插入/删除痕迹）、无批注
    #   ① word/document.xml 内无 w:ins / w:del（未接受的修订）
    #   ② 包内无 comments 部件（无批注）
    # 不同办公软件对齐：Word 与 WPS 的修订/批注都落在同一组 OOXML 部件与标签上。
    body_xmls = _parts_like(parts, 'word/document.xml')
    body_xml = body_xmls[0] if body_xmls else ''
    has_rev = ('<w:ins ' in body_xml or '<w:del ' in body_xml)
    has_cmt = any('comments' in n for n in names)
    r20_ok = (not has_rev and not has_cmt)
    if r20_ok:
        results.append("+1：无修订标记（插入/删除痕迹）、无批注")
    else:
        results.append("+0：无修订标记（插入/删除痕迹）、无批注")

    # +1：主标题字号 23.0—25.0pt 且居中
    #   ① 存在主标题段；② 其每个有字 run 生效字号落在 23.0—25.0pt（原稿 24.00pt）
    #   ③ 段落对齐方式为居中
    # 不同办公软件对齐：字号沿继承链解析；居中读 w:jc/@w:val="center"。
    tp = [p for p in paras[:zone_end] if p.text.strip() == MAIN_TITLE]
    title_size_ok = bool(tp) and all(
        SZ_TITLE[0] <= (_resolve_effective_size_pt(doc, r) or 0) <= SZ_TITLE[1]
        for r in tp[0].runs if r.text.strip())
    title_center_ok = bool(tp) and tp[0].alignment == WD_ALIGN_PARAGRAPH.CENTER
    r21_ok = (title_size_ok and title_center_ok)
    if r21_ok:
        results.append("+1：主标题字号 23.0—25.0pt 且居中")
    else:
        results.append("+0：主标题字号 23.0—25.0pt 且居中")

    # +1：「一、单选题」「二、判断题」字号 14.0—17.0pt
    #   ① 两个章节标题都存在（各 1 段）
    #   ② 其每个有字 run 生效字号落在 14.0—17.0pt（原稿 15.50pt）
    hp = [p for p in paras[:zone_end] if p.text.strip() in HEADS]
    head_sizes = {_resolve_effective_size_pt(doc, r) for p in hp for r in p.runs if r.text.strip()}
    r22_ok = (len(hp) == 2
              and all(s and SZ_HEAD[0] <= s <= SZ_HEAD[1] for s in head_sizes))
    if r22_ok:
        results.append("+1：「一、单选题」「二、判断题」字号 14.0—17.0pt")
    else:
        results.append("+0：「一、单选题」「二、判断题」字号 14.0—17.0pt")

    # +1：题干与选项文字颜色为黑色或自动
    #   ① 题干与选项的 run 不得设置非 000000 的显式颜色（未设置=自动，合规）
    # 不同办公软件对齐：w:color/@w:val="auto" 或缺省都视为自动色。
    color_bad = sum(1 for p in body for r in p.runs
                    if r.font.color is not None and r.font.color.rgb is not None
                    and str(r.font.color.rgb) != '000000')
    r23_ok = (color_bad == 0)
    if r23_ok:
        results.append("+1：题干与选项文字颜色为黑色或自动")
    else:
        results.append("+0：题干与选项文字颜色为黑色或自动")

    # +1：题干与选项段落为左对齐或两端对齐，且首行缩进绝对值 ≤1pt
    #   ① 对齐方式只允许左对齐 / 两端对齐（含各类两端对齐变体）/ 未设置（随样式默认）
    #   ② 首行缩进绝对值 ≤1pt（原稿题干与选项均顶格，既不缩进也不悬挂）
    # 不同办公软件对齐：读 w:jc 与 w:ind/@w:firstLine（缇）；@w:firstLineChars 由
    # python-docx 归一到磅值，正负都取绝对值以同时约束缩进与悬挂。
    indents = [(p.paragraph_format.first_line_indent.pt
                if p.paragraph_format.first_line_indent else 0.0) for p in body]
    aligns = {p.alignment for p in body}
    r24_ok = (all(abs(v) <= 1 for v in indents) and all(a in _ALIGN_OK for a in aligns))
    if r24_ok:
        results.append("+1：题干与选项段落为左对齐或两端对齐，且首行缩进绝对值 ≤1pt")
    else:
        results.append("+0：题干与选项段落为左对齐或两端对齐，且首行缩进绝对值 ≤1pt")

    # +1：题目区字体统一，正文与标题使用同一种字体，未混入第二种字体
    #   ① 把题干、选项、主标题、两个章节标题的全部有字 run 的生效字体汇成集合
    #   ② 集合大小必须为 1（标题只允许放大字号，不允许换字体）
    all_fonts = {f for f in set(fonts) | {(_resolve_effective_font(doc, r) or '')
                                          for p in hp + tp for r in p.runs if r.text.strip()} if f}
    r25_ok = (len(all_fonts) == 1)
    if r25_ok:
        results.append("+1：题目区字体统一，正文与标题使用同一种字体，未混入第二种字体")
    else:
        results.append("+0：题目区字体统一，正文与标题使用同一种字体，未混入第二种字体")

    # +1：文档属性洁净——作者/最后修改者/标题/备注不残留 untitled、anonymous、
    #     generated by、转换工具名等占位值
    #   ① docProps/core.xml 的作者、最后修改者、标题、主题、关键词、备注、类别
    #   ② docProps/custom.xml 的自定义属性文本
    #   ③ 以上文本中不得出现 untitled / anonymous / generated by / python-docx /
    #      pdf2word / wps / adobe / kingsoft / pdf to word / foxit 等占位或工具名
    # 说明：不看 docProps/app.xml 的 <Application>——它只反映"用哪个软件保存"，
    # 用 WPS 保存并不是缺陷，不应因此扣分。
    cp = doc.core_properties
    meta = ' '.join(str(x or '') for x in (cp.author, cp.last_modified_by, cp.title,
                                           cp.subject, cp.keywords, cp.comments, cp.category))
    for x in _parts_like(parts, 'docProps/custom.xml'):
        meta += ' ' + _plain_text(x)
    r26_ok = not any(k in meta.lower() for k in TOOLS + PLACEHOLDERS)
    if r26_ok:
        results.append("+1：文档属性洁净——作者/最后修改者/标题/备注不残留 untitled、anonymous、"
                       "generated by、转换工具名等占位值")
    else:
        results.append("+0：文档属性洁净——作者/最后修改者/标题/备注不残留 untitled、anonymous、"
                       "generated by、转换工具名等占位值")

    # ========== 将 results 反解为结构化 dim2_items ==========
    # 逐项按追加顺序对齐 _MAX_DELTAS_ORDER：解析每条 "+N：说明" 的 N 与 rule。
    if len(results) != len(_MAX_DELTAS_ORDER):
        # 顺序表与实际条目不一致：视为脚本内部错误，交给外层兜底
        raise RuntimeError(
            f"dim2 项数不一致：results={len(results)} vs order={len(_MAX_DELTAS_ORDER)}"
        )
    dim2_items = []
    total_score = 0
    for raw, max_delta in zip(results, _MAX_DELTAS_ORDER):
        # 格式约定：'+N：' 前缀 + 规则说明；命中 N=max_delta，未命中 N=0
        head, _, rule = raw.partition("：")
        try:
            delta = int(head.replace("+", "").strip())
        except ValueError:
            delta = 0
        hit = delta > 0
        dim2_items.append({
            "rule": rule,
            "max_delta": max_delta,
            "delta": max_delta if hit else 0,
            "hit": hit,
        })
        total_score += (max_delta if hit else 0)

    result["dim2_items"] = dim2_items
    result["total_score"] = total_score
    result["max_score"] = MAX_SCORE_TOTAL
    return result


