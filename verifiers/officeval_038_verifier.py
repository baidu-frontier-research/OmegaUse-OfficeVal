    #   ① 题号集合等于 1—510 的连续整数集（自动覆盖"无重号、无缺号"）
    #   ② 每道题号段去掉"N、"前缀后剩余正文长度 ≥4，即题干未丢文字
    # 不同办公软件对齐：题号段一律以"数字 + 全角顿号"开头（w:t 文本层判定），
    # 不依赖任何编号域/列表样式，Word 与 WPS 转换件口径一致。
    dan_no = sorted(dan)
    r01_ok = (dan_no == list(range(1, DAN_COUNT + 1)) and _stem_body_nonempty(dan_stems))
    if r01_ok:
        results.append("+5：单选题号 1—510 完整连续、无重号无缺号，且每道题干正文非空")
    else:
        results.append("+0：单选题号 1—510 完整连续、无重号无缺号，且每道题干正文非空")

    # +5：选项段共 2040 个，每题 A、B、C、D 四项齐全且按 A→B→C→D 顺序排列
    #   ① 选项段总数 == 510 × 4 == 2040
    #   ② 按出现顺序每 4 个一组，首字符依次为 A、B、C、D
    # 不同办公软件对齐：只看 w:t 文本首字符，不依赖自动编号。
    seq = [p.text.strip()[0] for p in opts]
