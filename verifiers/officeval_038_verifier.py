    # +5：1018 处全角括号全部完成答案回填，无空括号残留
    #   ① 510 道单选括号内为 A/B/C/D 之一，508 道判断括号内为 √/× 之一，合计 1018 处
    #   ② 题目区不存在空括号"（）"（含仅有空白的括号）
    # 不同办公软件对齐：文本层判定，与"手填/查找替换/脚本填"无关。
    filled = (sum(1 for v in dan.values() if v in ('A', 'B', 'C', 'D'))
              + sum(1 for v in pan.values() if v in ('√', '×')))
    empty_bracket = len(EMPTY_BRACKET_RE.findall(qfull))
    r07_ok = (filled == BRACKET_COUNT and empty_bracket == 0)
    if r07_ok:
        results.append("+5：1018 处全角括号全部完成答案回填，无空括号残留")
    else:
        results.append("+0：1018 处全角括号全部完成答案回填，无空括号残留")

    # +5：1018 处答案与标准答案逐条一致，无一处错填
