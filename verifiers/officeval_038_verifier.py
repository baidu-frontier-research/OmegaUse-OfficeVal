    # ========== 维度1：可用与可修改性（门槛，不计分） ==========
    # 任一条不满足即整份交付判定为不可用：dim2_items 为空、total_score 记 0。
    dim1_ok, dim1_reason = _check_dimension_one(file_path)
    result["dim1_pass"] = bool(dim1_ok)
    result["dim1_reason"] = dim1_reason
    if not dim1_ok:
        result["dim2_items"] = []
        result["total_score"] = 0
        result["max_score"] = MAX_SCORE_TOTAL
        return result

    doc = _open_word_document(file_path)
    names, parts = _read_package_parts(file_path)
    results = []

    # --- 公共取件：题目区 / 题号段 / 选项段 / 回填结果 ---
    paras = list(doc.paragraphs)
    texts = [p.text for p in paras]
    zone_end = _question_zone_end(texts)          # 答案区起点，其后全部不检查
    qtexts = texts[:zone_end]                     # 题目区段落文本
    qfull = '\n'.join(qtexts)
    stems = [p for p in paras[:zone_end] if STEM_RE.match(p.text.strip())]
    opts = [p for p in paras[:zone_end] if OPT_RE.match(p.text.strip())]
    body = stems + opts                           # 题干 + 选项，即"正文"
    dan, pan, blocks = _collect_filled_answers(texts, zone_end)
    # 按章节标题把题号段分入单选区 / 判断区（供两条题号完整性规则分别取用）
    dan_stems, pan_stems, _sec = [], [], 'dan'
    for _p in paras[:zone_end]:
        _s = _p.text.strip()
        if _s == HEADS[1]:
            _sec = 'pan'
            continue
        if _s == HEADS[0]:
            _sec = 'dan'
            continue
        if STEM_RE.match(_s):
            (pan_stems if _sec == 'pan' else dan_stems).append(_p)

    def _stem_body_nonempty(plist):
        """题号段去掉"N、"前缀后仍有 ≥4 个字符，视为题干正文非空。"""
        return all(len(re.sub(r'^\d+、', '', p.text.strip())) >= 4 for p in plist)

    # ========== 维度2：完成度评分（26 条 / 满分 78 分） ==========

