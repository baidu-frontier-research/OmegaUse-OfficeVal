    # +5：文字层无乱码替换字符、无私用区字符、无半角括号 ()、无相邻重复段落
    #   ① 无 U+FFFD 替换字符（PDF 抽取失败的典型残留）
    #   ② 无 Unicode 私用区字符 U+E000—U+F8FF（嵌入字型映射丢失的典型残留）
    #   ③ 汉字紧邻的括号不得是半角 ( )：中文题面应统一用全角（）
    #   ④ 无相邻两段文字完全相同（PDF 转换重复吐字）
