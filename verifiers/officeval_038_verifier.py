def _is_songti(name):
    """宋体系判定：SimSun / 宋体 / NSimSun / New SimSun / 中易宋体 视为同一字体族。"""
    return bool(name) and any(k in str(name).lower() for k in SONG)


def _is_gray(hexv):
    """灰色判定：RGB 三通道极差 ≤40（无明显色相）且平均亮度落在 0x60—0xC0。"""
    v = str(hexv).upper()
    try:
        r, g, b = (int(v[i:i + 2], 16) for i in (0, 2, 4))
    except (ValueError, IndexError):
        return False
    return max(r, g, b) - min(r, g, b) <= 40 and 0x60 <= (r + g + b) // 3 <= 0xC0


def _read_package_parts(file_path):
    """读取 .docx（OOXML zip 包）内全部 XML 部件的原始文本。
       python-docx 只暴露正文对象模型，页眉/水印/文档属性等需直接看 XML。"""
    parts = {}
    with zipfile.ZipFile(file_path) as zf:
        names = list(zf.namelist())
        for n in names:
            if n.lower().endswith(('.xml', '.rels')):
                parts[n] = zf.read(n).decode('utf-8', 'ignore')
    return names, parts


def _parts_like(parts, frag):
    """取部件名包含 frag 的所有 XML 文本（如 'word/header' 命中 header1/2/3.xml）。"""
    return [xml for name, xml in sorted(parts.items()) if frag in name]


def _plain_text(xml):
    """剥掉标签，得到 XML 部件里的可见文字。"""
    return re.sub(r'<[^>]+>', '', xml)


def _resolve_effective_eastasia(doc, run):
    """按 Word 的字体继承链，解析 run 中文字符实际生效的东亚字体（打开办公软件看到的）：
       run 直接设定(w:eastAsia) → 段落样式(含 basedOn 链) → docDefaults。
       任一层拿到即返回；都没有则返回 None。"""
    # 1) run 级
    rPr = run._element.rPr
    if rPr is not None:
        rFonts = rPr.find(qn('w:rFonts'))
        if rFonts is not None:
            ea = rFonts.get(qn('w:eastAsia'))
            if ea:
                return ea
    # 2) 段落样式链（w:pStyle → styles.xml，沿 basedOn 上溯）
    styles_el = doc.styles.element
    para = run._parent
    style_id = None
    try:
        pPr = para._p.find(qn('w:pPr'))
        if pPr is not None:
            pStyle = pPr.find(qn('w:pStyle'))
            if pStyle is not None:
                style_id = pStyle.get(qn('w:val'))
    except Exception:
        style_id = None

    def _style_by_id(sid):
        for st in styles_el.findall(qn('w:style')):
            if st.get(qn('w:styleId')) == sid:
                return st
        return None

    seen = set()
    while style_id and style_id not in seen:
        seen.add(style_id)
        st = _style_by_id(style_id)
        if st is None:
            break
        rpr = st.find(qn('w:rPr'))
        if rpr is not None:
            rf = rpr.find(qn('w:rFonts'))
            if rf is not None:
                ea = rf.get(qn('w:eastAsia'))
                if ea:
                    return ea
        base = st.find(qn('w:basedOn'))
        style_id = base.get(qn('w:val')) if base is not None else None

    # 3) docDefaults
    dd = styles_el.find(qn('w:docDefaults'))
    if dd is not None:
        rpd = dd.find(qn('w:rPrDefault'))
        if rpd is not None:
            rpr = rpd.find(qn('w:rPr'))
            if rpr is not None:
                rf = rpr.find(qn('w:rFonts'))
                if rf is not None:
                    ea = rf.get(qn('w:eastAsia'))
                    if ea:
                        return ea
    return None


def _resolve_effective_ascii(doc, run):
    """按 Word 的字体继承链，解析 run 对西文/数字实际生效的字体（打开办公软件看到的）：
       run 直接设定(w:ascii → 回落 w:hAnsi) → 段落样式(含 basedOn 链) → docDefaults。
       任一层拿到即返回；都没有则返回 None。"""
    def _ascii_of(rFonts):
        if rFonts is None:
            return None
        return rFonts.get(qn('w:ascii')) or rFonts.get(qn('w:hAnsi'))

    # 1) run 级
    rPr = run._element.rPr
    if rPr is not None:
        v = _ascii_of(rPr.find(qn('w:rFonts')))
        if v:
            return v
    # 2) 段落样式链
    styles_el = doc.styles.element
    para = run._parent
    style_id = None
    try:
        pPr = para._p.find(qn('w:pPr'))
        if pPr is not None:
            pStyle = pPr.find(qn('w:pStyle'))
            if pStyle is not None:
                style_id = pStyle.get(qn('w:val'))
    except Exception:
        style_id = None

    def _style_by_id(sid):
        for st in styles_el.findall(qn('w:style')):
            if st.get(qn('w:styleId')) == sid:
                return st
        return None

    seen = set()
    while style_id and style_id not in seen:
        seen.add(style_id)
        st = _style_by_id(style_id)
        if st is None:
            break
        rpr = st.find(qn('w:rPr'))
        if rpr is not None:
            v = _ascii_of(rpr.find(qn('w:rFonts')))
            if v:
                return v
        base = st.find(qn('w:basedOn'))
        style_id = base.get(qn('w:val')) if base is not None else None

    # 3) docDefaults
    dd = styles_el.find(qn('w:docDefaults'))
    if dd is not None:
        rpd = dd.find(qn('w:rPrDefault'))
        if rpd is not None:
            rpr = rpd.find(qn('w:rPr'))
            if rpr is not None:
                v = _ascii_of(rpr.find(qn('w:rFonts')))
                if v:
                    return v
    return None


def _resolve_effective_font(doc, run):
    """题干/选项以中文为主，取实际生效的东亚字体；东亚字体缺省时回落到西文字体
       （WPS/Word 转换件常只写 w:ascii/w:hAnsi），保证"打开后眼睛看到的字体"口径一致。"""
    return _resolve_effective_eastasia(doc, run) or _resolve_effective_ascii(doc, run)


def _resolve_effective_size_pt(doc, run):
    """按 Word 的继承链解析 run 实际生效的字号（磅）：
       run 直接设定(w:sz) → 段落样式(含 basedOn 链) → docDefaults；都没有返回 None。
       w:sz 以半磅存储，故除 2。"""
    try:
        if run.font.size is not None:
            return run.font.size.pt
    except Exception:
        pass
    st, depth = run._parent.style, 0
    while st is not None and depth < 8:
        try:
            if st.font.size is not None:
                return st.font.size.pt
        except Exception:
            pass
        st, depth = st.base_style, depth + 1
    dd = doc.styles.element.find(qn('w:docDefaults'))
    if dd is not None:
        rpd = dd.find(qn('w:rPrDefault'))
        if rpd is not None:
            rpr = rpd.find(qn('w:rPr'))
            if rpr is not None:
                sz = rpr.find(qn('w:sz'))
                if sz is not None and sz.get(qn('w:val')):
                    try:
                        return int(sz.get(qn('w:val'))) / 2.0
                    except ValueError:
                        return None
    return None


